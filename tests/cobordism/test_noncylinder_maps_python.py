# disjointUnion guards.
# --------------------------------------------------------------------------- #
class TestDisjointUnionGuards(unittest.TestCase):

    def test_rejects_empty_input(self):
        empty = tessera.Spacetime()
        with self.assertRaises((ValueError, RuntimeError)):
            Cobordism.disjointUnion(empty, _solid_torus())

    def test_rejects_mismatched_top_dimension(self):
        # A solid torus (3-manifold) and a bare surface (2-manifold) differ in
        # top dimension and cannot be disjoint-unioned as same-dim complexes.
        with self.assertRaises((ValueError, RuntimeError)):
            Cobordism.disjointUnion(_solid_torus(), _torus9())


