"""Which operations U on Z(T^2)=C^4 are Dijkgraaf-Witten realizable.

The companion runnable for the realizable-image report (#194), the payoff to the
twisted-cylinder builder (#193). It re-runs the labeled operation sweep against
the *enriched* realizable DW 2-boundary map image and reports the now
non-degenerate separating property.

Background. The DW functor sends a cobordism W : T^2 -> T^2 to a linear map on
Z(T^2) = C[H^1(T^2;Z_2)] = C^4 (the flat-Z_2-connection basis, classes indexed
0=[trivial], 1=[a], 2=[b], 3=[a+b]). With only the order-preserving product
cylinder available the realizable image was the single point {I_4}, so the
realizability question "what distinguishes a DW-realizable U" was degenerate.
``Cobordism.twistedCylinder(Sigma, phi)`` threads the two boundary copies of
Sigma through a finite-order simplicial automorphism phi, and ``Dijkgraaf
Witten.map()`` returns the permutation phi induces on the holonomy classes. Two
generators suffice:

  * the coordinate swap phi:(u,v)->(v,u) on the 9-vertex product torus
    T^2 = SimplicialProduct(dDelta^2, dDelta^2) -- the transposition (1 2) that
    exchanges [a]<->[b] and fixes [0],[a+b];
  * the multiplier i->2i (mod 7) on the 7-vertex Moebius torus -- the order-3
    rotation (1 2 3) that cycles [a]->[b]->[a+b] and fixes [0].

Generated by matrix multiplication these two close to a group of exactly 6
elements: the full S_3 on the three non-trivial classes, fixing the trivial one
-- the permutation representation of GL(2,Z_2) = SL(2,Z_2) acting on
H^1(T^2;Z_2). That is the realizable set.

The sweep then reads >= 150 labeled operations U (4x4) through the genuine
machinery (``DijkgraafWitten.amplitude``, ``ChoiJamiolkowski.transition
Amplitude``, ``BoundaryStateSpace.state``) and records, for each,

  * gap_to_S3 = min over the 6 realizable maps g of ||U - g||  (the live metric);
  * gap_to_I4 = ||U - I_4||                                    (the old metric);
  * realizable := gap_to_S3 < tol;

plus the candidate separating properties. The discriminating family is the full
24 of S_4's 4x4 permutation matrices: exactly the 6 that fix index 0 (and so
permute {1,2,3}) are realizable, the other 18 are not -- the clean separation.

The separator. realizable(U) <=> U is a 0/1 permutation matrix fixing the
trivial class index 0 <=> U is the permutation rep of a GL(2,Z_2) automorphism
of H^1(T^2;Z_2). The fact that *every* permutation of the three non-trivial
classes is GF(2)-linear (any two distinct non-zero vectors of (Z_2)^2 are a
basis, so the image of [a+b] is forced to the sum) is exactly why the realizable
image is the *full* S_3 and not a proper subgroup -- and why distance-to-S_3,
not distance-to-I_4, now governs the gap.

Run:  python examples/cobordism/realizable_image_sweep.py
      (--help for options; the raw full sweep table defaults to /tmp/cobordism
      and is NOT committed -- attach it to the issue/PR to pin a result. The
      script is the committed artifact.)

Exit status is 0 iff the verdicts match expectation: the six DW maps close to
S_3; of the 24 permutations exactly the 6 holonomy ones are realizable; I_4 is
realizable; and a Haar/Hadamard sample is not.
"""

