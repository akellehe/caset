def _perm_str(perm):
    return "[" + " ".join(str(perm[i]) for i in range(DIM)) + "]"


def write_full_table(out_dir, rows):
    """Write the raw full sweep table (PR artifact, NOT committed to the tree)."""
    os.makedirs(out_dir, exist_ok=True)
    fields = list(rows[0].keys())
    csv_path = os.path.join(out_dir, "realizable_image_sweep.csv")
    with open(csv_path, "w", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=fields)
        writer.writeheader()
        for row in rows:
            writer.writerow(row)
    md_path = os.path.join(out_dir, "realizable_image_sweep.md")
    with open(md_path, "w") as handle:
        handle.write("# Realizable-image operation sweep (raw full table)\n\n")
        handle.write(f"- Operations swept: **{len(rows)}**\n")
        handle.write("- `gap_to_S3` = min over the 6 S_3 DW maps of ||U - g||; "
                     "`realizable := gap_to_S3 < 1e-7`.\n")
        handle.write("- `gap_to_I4` = ||U - I_4|| (the old single-point metric).\n\n")
        handle.write("| " + " | ".join(fields) + " |\n")
        handle.write("|" + "|".join(["---"] * len(fields)) + "|\n")
        for row in rows:
            handle.write("| " + " | ".join(_fmt(row[f]) for f in fields) + " |\n")
    return csv_path, md_path


# --------------------------------------------------------------------------- #
# Self-check: the verdicts the report rests on.
# --------------------------------------------------------------------------- #
def verify(image, sweep):
    rows_by_label = {r["label"]: r for r in sweep.rows}
    # The six DW maps close to S_3 (asserted inside certify()).
    assert len(image.maps) == 6
    # Of the 24 permutations exactly the 6 holonomy ones are realizable.
    verdict = sweep.permutation_verdict()
    assert verdict["total"] == 24 and verdict["realizable"] == 6, verdict
    # I_4 realizable (read both as the S_3 identity and the perm identity); a
    # Haar / Hadamard sample is not.
    assert rows_by_label["s3_0123"]["realizable"] == 1
    assert rows_by_label["perm_0123"]["realizable"] == 1
    assert rows_by_label["haar_0"]["realizable"] == 0
    assert rows_by_label["hadamard4"]["realizable"] == 0
    # The separator is clean: is_holonomy_perm has zero false +/-.
    separator = sweep.separator_table()
    key = "is_holonomy_perm (fixes [0] & permutes {1,2,3})"
    assert separator[key]["separates"], separator[key]


